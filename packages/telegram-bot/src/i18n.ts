export type BotLocale = 'en' | 'ru';

export function toBotLocale(value: unknown): BotLocale {
  if (value === 'ru') return 'ru';
  if (typeof value === 'string' && value.toLowerCase().startsWith('ru')) return 'ru';
  return 'en';
}

